"""Empirical calibration of a house_lib world (design §5), before it is used. Not run in CI.

Two filters on dev seeds, per lesson, from the lesson checks (`lesson:<id>`) of the verdicts:

- guessability: group A (no hints) passes the lesson's check in more than GUESS_MAX of episodes
  -> the lesson is guessable: drop or redraw it;
- learnability: P-task (the gold text of the task's own lessons in the first message) passes it in
  less than LEARN_MIN -> the model can't follow it even when told: drop it. Until 2026-11-02 this
  was P-hand (the whole handbook), which mixed in the handbook's length: in L16-c0 the same
  `partner_format` lessons passed 57-70% of checks there against 70-92% in L4 (design §10).

What exists here: the task panel (`calibration_tasks`), the handbook (`handbook_lines`; the P-hand
group in elh/batch.py shows one item per line) and the filter (`filter_lessons`). Not implemented:
the runs, which need the GPU (~1,000 episodes for the core grid's six worlds, design §8). A run then
passes its verdicts' `checks` to `filter_lessons`.
"""

from __future__ import annotations

import random
from collections import defaultdict
from dataclasses import dataclass

GUESS_MAX = 0.20
LEARN_MIN = 0.60
DEV_SEEDS = (3000, 4000)


def handbook_lines(family) -> list[str]:
    """P-hand / W-hand content: the gold text of every lesson in the world, in catalogue order."""
    from elh.tasks.families.house_lib.lessons import gold_text

    return [gold_text(les) for les in family.world.lessons]


def handbook(family) -> str:
    return "\n".join(f"- {line}" for line in handbook_lines(family))


def calibration_tasks(family, per_lesson: int = 4, seed: int = 0) -> list[tuple[str, str, int]]:
    """(cause, theme, seed) on dev seeds: `per_lesson` tasks with each lesson as the primary one,
    themes spread round-robin. Secondary and module-wide lessons add further observations."""
    rng = random.Random(f"house_lib/calibration/{family.name}/{seed}")
    themes = list(family.themes)
    rng.shuffle(themes)
    out, s = [], DEV_SEEDS[0]
    for lesson in family.causes:
        for i in range(per_lesson):
            out.append((lesson, themes[i % len(themes)], s))
            s += 1
    if s > DEV_SEEDS[1]:
        raise ValueError(f"calibration panel needs {s - DEV_SEEDS[0]} dev seeds; only {DEV_SEEDS[1] - DEV_SEEDS[0]} exist")
    return out


# Calibration batch names per world seed: w1's are exp21 (A, P-hand) and exp24 (P-task); the sealed
# study's new worlds (w2, roadmap 2026-11-07) use exp40 and exp41 with the same panel and settings.
BATCH_PREFIXES = {1: ("exp21-calib", "exp24-learn"), 2: ("exp40-calib", "exp41-learn")}


def batch_prefixes(world: str) -> tuple[str, str]:
    from elh.tasks.families.house_lib.lessons import parse_world_id

    return BATCH_PREFIXES[parse_world_id(world)[2]]


def batch_texts(family, per_lesson: int = 8) -> tuple[str, str]:
    """The text of the world's two calibration batch files: (calib: groups A and P-hand; learn: group
    P-task), both on `calibration_tasks(family, per_lesson)`. For w1 everything from `name:` on
    reproduces the committed exp21 / exp24 files."""
    world, (calib, learn) = family.world.id, batch_prefixes(family.world.id)
    items = "".join(f"      - [{c}, {t}, {s}]\n" for c, t, s in calibration_tasks(family, per_lesson))
    n = len(items.splitlines())

    def body(name: str, groups: str) -> str:
        return (f"name: {name}-{world}\nbase_config: experiments/phase0-local.yaml\noverrides:\n"
                "  memory_service.record_format: lesson-v3\n  memory_service.recall_types: [experience]\n"
                "  memory_service.agent_search: true\n  memory_service.experience_position: after_ticket\n"
                "  rules: {enabled: true, store: verbatim}\n"
                f"family: house_lib/{world}\nhistories: 1\ngroups: [{groups}]\nphases:\n- eval:\n"
                f"    label: calibration\n    tasks:\n      items:\n{items}")

    note = ("Settings and panel rule as w1's exp21 / exp24, for the sealed study's new world seed (core-grid\n"
            "# §10, 2026-11-07). Generated by `calibration.batch_texts`; tests/test_house_lib.py checks the items.\n")
    head_calib = (
        f"# house_lib calibration (design §5, phase 2) for world {world}: groups A (no hints) and P-hand\n"
        "# (the world's handbook) on the dev-seed panel `calibration.calibration_tasks(family, per_lesson=8)`,\n"
        f"# {n} tasks, so {2 * n} episodes. Feeds `calibration.filter_lessons`: a lesson A passes in more\n"
        "# than 20% of its checks is guessable; one P-hand passes in under 60% is not learnable. Memory settings\n"
        "# match the core grid's B: the memory block goes right after the ticket (design §10, 2026-11-01).\n"
        f"# {note}")
    head_learn = (
        f"# house_lib learnability control for world {world} (design §5, §10 decision 2026-11-02): group P-task, the\n"
        "# handbook lines of each ticket's own lessons only, on the calibration panel (`calibration_tasks(family,\n"
        f"# per_lesson=8)`, {n} tasks, {n} episodes). With the calibration's group A it feeds `calibration.filter_lessons`\n"
        "# (told=\"P-task\"); the calibration's P-hand (the whole handbook) stays as the comparison that measures the\n"
        f"# handbook's length. {note}")
    return head_calib + body(calib, "A, P-hand"), head_learn + body(learn, "P-task")


@dataclass
class LessonCalibration:
    lesson: str
    a_n: int
    a_rate: float | None
    hand_n: int
    hand_rate: float | None
    keep: bool
    reason: str


def filter_lessons(episodes: list[dict], lessons: list[str], told: str = "P-task") -> list[LessonCalibration]:
    """`episodes`: one dict per graded episode, {"group": "A" | told, "checks": verdict.checks};
    `told` is the learnability group.
    A lesson with no observations in a group is kept undecided (reason says so)."""
    seen: dict[tuple[str, str], list[bool]] = defaultdict(list)
    for ep in episodes:
        for name, ok in ep["checks"].items():
            if name.startswith("lesson:"):
                seen[ep["group"], name.removeprefix("lesson:")].append(bool(ok))
    out = []
    for lid in lessons:
        a, h = seen.get(("A", lid), []), seen.get((told, lid), [])
        a_rate = sum(a) / len(a) if a else None
        h_rate = sum(h) / len(h) if h else None
        if a_rate is not None and a_rate > GUESS_MAX:
            keep, reason = False, f"guessable: A passes {a_rate:.0%} > {GUESS_MAX:.0%}"
        elif h_rate is not None and h_rate < LEARN_MIN:
            keep, reason = False, f"not learnable: {told} passes {h_rate:.0%} < {LEARN_MIN:.0%}"
        elif a_rate is None or h_rate is None:
            keep, reason = True, "undecided: missing observations"
        else:
            keep, reason = True, "kept"
        out.append(LessonCalibration(lid, len(a), a_rate, len(h), h_rate, keep, reason))
    return out
